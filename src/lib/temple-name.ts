/**
 * 廟名的「一般稱呼」——**只給顯示層用**，資料層的 `name` 永遠是廟方的登記全名，不改。
 *
 * 為什麼要有這支（2026-08-09，GSC 實測）：
 *   站上 348 間廟的登記全名以「財團法人／社團法人」開頭，SERP 上看到的字就長成
 *   「財團法人高雄市憲德宮・…」。實測這群 7 天 7,977 曝光只換到 109 點擊（CTR 1.37%），
 *   其餘 10,342 間是 97,648 曝光 2,365 點擊（2.42%）——同頁型、同 SERP 環境，**差 43%**。
 *   最極端的 `moi_3449`（憲德宮）7 天 2,239 曝光只有 2 次點擊（0.09%），是全站曝光第一名的頁。
 *   而「財團法人」這串字**本身沒有搜尋需求**：同期 6,339 個查詢詞裡只有 11 個含這四字，
 *   合計 81 曝光、**0 點擊**；使用者搜的是「憲德宮」（單這一詞就 1,144 曝光）。
 *
 * 🔴 **不是截字，是拿掉法人前綴後把一般稱呼放前面**。`docs/decisions/temples.md` 有一條
 *    2026-07-31 的判準：「不該為了湊字數去截廟方的登記全名——廟名正是使用者搜的字」。
 *    那條仍然成立且與本支不衝突：這裡拿掉的是**沒有人搜的**法人前綴，留下的正是被搜的那幾個字，
 *    且登記全名在 `<h1>`、meta description、頁面內文一字不少。**不要把本支拿去截字。**
 *
 * ⚠️ **只對法人開頭的名稱動手**。不加這道閘的話，像「台南市歸仁區仁壽宮」這種
 *    本來就以縣市開頭的登記名也會被剝掉縣市，那是改到不該改的 10,342 間。
 */

/** 縣市前綴（含臺/台兩種寫法）。與 `temple-region.ts` 的 COUNTIES 同源，但那支是「由地址推導」、
 *  本支是「由廟名剝前綴」，用途不同故不共用——共用會讓任一邊的規則改動誤傷另一邊。 */
const COUNTY_PREFIX =
  /^(台北市|臺北市|新北市|基隆市|桃園市|新竹市|新竹縣|苗栗縣|台中市|臺中市|彰化縣|南投縣|雲林縣|嘉義市|嘉義縣|台南市|臺南市|高雄市|屏東縣|宜蘭縣|花蓮縣|台東縣|臺東縣|澎湖縣|金門縣|連江縣)/;

const LEGAL_PREFIX = /^(財團法人|社團法人)/;

/** 剝完之後至少要剩幾個字才採用。低於這個數就整段退回登記全名（寧可難看，不可空白）。 */
const MIN_KEEP = 2;

/**
 * 登記全名 → 一般稱呼。非法人開頭者原樣回傳（絕大多數廟走這條）。
 *
 * 實例：
 *   財團法人高雄市憲德宮           → 憲德宮
 *   財團法人財團法人臺中市眉山福安宮 → 眉山福安宮（法人前綴重複登記，故用 while 剝到乾淨）
 *   財團法人台灣省花蓮縣花蓮港天宮  → 花蓮港天宮
 *   財團法人台北行天宮北投分宮      → 台北行天宮北投分宮（「台北」不是「台北市」，縣市閘不觸發）
 *   財團法人軒轅教                 → 軒轅教（沒有宮廟字也照剝，教派登記名是合法的一般稱呼）
 */
export function commonTempleName(name: string): string {
  if (!LEGAL_PREFIX.test(name)) return name;
  let s = name;
  while (LEGAL_PREFIX.test(s)) s = s.replace(LEGAL_PREFIX, '');
  s = s.replace(/^(台灣省|臺灣省)/, '');
  s = s.replace(COUNTY_PREFIX, '');
  s = s.trim();
  return [...s].length >= MIN_KEEP ? s : name;
}

/** 這個名稱是否被剝過（＝值得在 title 補一個「（登記全名）」）。 */
export function hasLegalPrefix(name: string): boolean {
  return commonTempleName(name) !== name;
}
